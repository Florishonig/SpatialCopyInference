#' @title Plot genomic clusters by chromosome
#'
#' @description
#' Generates chromosome-level visualisations of genomic
#' clusters identified by identify_gene_clusters().
#'
#' Differentially expressed genes are displayed along
#' the genomic coordinate space of each chromosome and
#' coloured according to the size of the cluster to
#' which they belong. Genomic cluster boundaries are
#' highlighted, and optional genomic density tracks and
#' driver gene annotations can be overlaid.
#' One figure is generated per chromosome. Plots can be
#' displayed in the active graphics device or saved to a
#' specified output directory.
#'
#' @param gene_clusters Output from
#' identify_gene_clusters()
#' @param chromosome Optional chromosome or vector of
#' chromosomes to plot (e.g. "chr3" or
#' c("chr3", "chr8")). If NULL, all chromosomes are
#' plotted
#' @param density Optional genomic density signal
#' generated by plot_gene_density()
#' @param driver_genes Optional vector of driver genes
#' to annotate
#' @param raised_driver_genes Optional subset of driver
#' genes displayed on a separate annotation track to
#' reduce label overlap
#' @param output_dir Optional directory in which
#' chromosome plots will be saved. If NULL, plots are
#' displayed in the active graphics device.
#'
#' @importFrom S4Vectors mcols mcols<-
#'
#' @returns An invisible list containing the annotated
#' differentially expressed gene ranges (`gr_de`) and
#' driver gene ranges (`gr_drivers`) used for
#' visualisation.
#'
#' @export
plot_gene_clusters_by_chromosome <- function(
    gene_clusters,
    chromosome = NULL,
    density = NULL,
    driver_genes = NULL,
    raised_driver_genes = NULL,
    output_dir = NULL
){

  if (is.null(raised_driver_genes)) {
    raised_driver_genes <- character(0)
  }

  gr_de <- gene_clusters$gr_de
  cluster_df <- gene_clusters$cluster_assignments

  rownames(cluster_df) <- NULL

  match_idx <- match(
    gr_de$gene,
    cluster_df$gene
  )

  gr_de$cluster <- cluster_df$cluster_global[
    match_idx
  ]

  gr_de$cluster_size <- cluster_df$cluster_size_cat[
    match_idx
  ]

  cols <- c(
    "2"  = "#8dd3c7",
    "3"  = "#80b1d3",
    "4"  = "#bebada",
    "5+" = "#fb8072"
  )


  gr_de$col <- "grey80"

  has_cluster <- !is.na(
    gr_de$cluster_size
  )

  gr_de$col[has_cluster] <- cols[
    as.character(
      gr_de$cluster_size[has_cluster]
    )
  ]

  # Rectangle colours
  cluster_cols <- c(
    "2"  = scales::alpha("#8dd3c7", 0.4),
    "3"  = scales::alpha("#80b1d3", 0.4),
    "4"  = scales::alpha("#bebada", 0.4),
    "5+" = scales::alpha("#fb8072", 0.4)
  )

  # Create genomic ranges
  gr <- GenomicRanges::GRanges(
    seqnames = hg38_gene_info$chrom,
    ranges = IRanges::IRanges(
      start = hg38_gene_info$start_position,
      end = hg38_gene_info$end_position
    ),
    gene = hg38_gene_info$hgnc_symbol
  )

  # Driver genes
  if (!is.null(driver_genes)) {

    gr_drivers <- gr[
      gr$gene %in% driver_genes
    ]

  } else {

    gr_drivers <- GenomicRanges::GRanges()

  }

  chr_lengths <- setNames(
    hg38_chrom_info$length,
    hg38_chrom_info$chrom
  )

  chroms <- if(is.null(chromosome)) {
    paste0("chr", c(1:22, "X"))
  } else {
    chromosome
  }

  save_plots <- !is.null(output_dir)

  if(save_plots) {
    dir.create(
      output_dir,
      recursive = TRUE,
      showWarnings = FALSE
    )
  }

  for (chr in chroms) {

    if(save_plots) {
      png(
        filename = file.path(
          output_dir,
          paste0(chr, ".png")
        ),
        width = 2000,
        height = 1000,
        res = 300
      )
    }

    sub <- gr_de[
      seqnames(gr_de) == chr
    ]

    # Build rectangles for this chromosome only
    sub_cluster <- sub[
      !is.na(sub$cluster)
    ]

    if (length(sub_cluster) > 0) {

      cluster_gr_chr <- unlist(
        GenomicRanges::GRangesList(
          lapply(
            split(
              sub_cluster,
              sub_cluster$cluster
            ),
            function(gr) {


              cluster_size <- unique(
                gr$cluster_size
              )[1]


              GenomicRanges::GRanges(
                seqnames = seqnames(gr)[1],
                ranges = IRanges::IRanges(
                  start = min(start(gr)),
                  end = max(end(gr))
                ),
                size = cluster_size
              )
            }
          )
        )
      )

      mcols(cluster_gr_chr)$col_rect <- cluster_cols[
        as.character(
          mcols(cluster_gr_chr)$size
        )
      ]

    } else {

      cluster_gr_chr <- GenomicRanges::GRanges()

    }

    plot.params <- karyoploteR::getDefaultPlotParams(
      plot.type = 2
    )

    plot.params$ideogramheight <- 20
    plot.params$data1height <- 1000
    plot.params$data2height <- 200
    plot.params$bottommargin <- 0
    plot.params$topmargin <- 0

    kp <- karyoploteR::plotKaryotype(
      plot.params = plot.params,
      genome = "hg38",
      plot.type = 2,
      zoom = paste0(
        chr,
        ":1-",
        chr_lengths[chr]
      )
    )

    if(!is.null(density)) {

      density_chr <- density[
        seqnames(density) == chr
      ]

      karyoploteR::kpRect(
        kp,
        data = density_chr,
        data.panel = 2,
        y0 = 0,
        y1 = 0.2,
        col = scales::alpha(
          density_chr$col,
          0.9
        ),
        border = NA
      )
    }

    # Draw rectangles
    if (length(cluster_gr_chr) > 0) {


      karyoploteR::kpRect(
        kp,
        data = cluster_gr_chr,
        y0 = 0,
        y1 = 0.9,
        col = mcols(
          cluster_gr_chr
        )$col_rect,
        border = NA
      )
    }

    if (length(sub) > 0) {

      sub <- sub[
        sample(length(sub))
      ]

      ord <- order(
        start(sub)
      )

      sub <- sub[ord]

      n <- length(sub)

      ys <- numeric(n)

      window <- 10

      base_levels <- c(
        seq(
          0.05,
          0.45,
          length.out = 8
        ),
        seq(
          0.55,
          0.95,
          length.out = 8
        )
      )

      for (i in seq_len(n)) {

        if (i > 1) {

          prev_idx <- seq(
            max(1, i - window),
            i - 1
          )

          used <- ys[prev_idx]

        } else {

          used <- numeric(0)

        }

        available <- setdiff(
          base_levels,
          used
        )

        if (length(available) == 0) {
          available <- base_levels
        }

        if (i > 1) {
          available <- setdiff(
            available,
            ys[i - 1]
          )
        }

        if (length(available) == 0 && i > 1) {
          available <- setdiff(
            base_levels,
            ys[i - 1]
          )
        }


        if (length(available) == 0) {
          available <- base_levels
        }


        ys[i] <- sample(
          available,
          1
        )
      }


      ys <- jitter(
        ys,
        amount = 0.01
      )


      karyoploteR::kpPoints(
        kp,
        data = sub,
        col = sub$col,
        cex = 0.8,
        y = 0.5
      )


      has_cluster <- !is.na(
        sub$cluster
      )


      if (any(has_cluster)) {


        karyoploteR::kpSegments(
          kp,
          chr = chr,
          x0 = start(
            sub[has_cluster]
          ),
          x1 = start(
            sub[has_cluster]
          ),
          y0 = 0.5,
          y1 = ys[has_cluster],
          col = "grey60",
          lty = 2
        )


        karyoploteR::kpText(
          kp,
          data = sub[has_cluster],
          labels = sub$gene[
            has_cluster
          ],
          y = ys[has_cluster],
          col = sub$col[
            has_cluster
          ],
          cex = 0.7
        )
      }
    }

    # Driver genes on current chromosome
    if (length(gr_drivers) > 0) {

      drivers_chr <- gr_drivers[
        as.character(seqnames(gr_drivers)) == chr
      ]

      if (length(drivers_chr) > 0) {

        karyoploteR::kpPoints(
          kp,
          data = drivers_chr,
          y = rep(0, length(drivers_chr)),
          col = "#ffed6f",
          cex = 1.2,
          pch = 17
        )

        # Standard driver labels
        standard_drivers <- drivers_chr[
          !drivers_chr$gene %in% raised_driver_genes
        ]

        if (length(standard_drivers) > 0) {

          karyoploteR::kpPlotMarkers(
            kp,
            data = standard_drivers,
            labels = standard_drivers$gene,
            text.orientation = "horizontal",
            adjust.label.position = FALSE,
            line.color = scales::alpha(
              "white",
              0.01
            ),
            label.color = "black",
            r0 = 0,
            r1 = 0.05,
            cex = 0.7
          )
        }

        # Raised driver labels
        if (!is.null(raised_driver_genes) &&
            length(raised_driver_genes) > 0) {

          raised_drivers_chr <- drivers_chr[
            drivers_chr$gene %in% raised_driver_genes
          ]

          if (length(raised_drivers_chr) > 0) {

            karyoploteR::kpPlotMarkers(
              kp,
              data = raised_drivers_chr,
              labels = raised_drivers_chr$gene,
              text.orientation = "horizontal",
              adjust.label.position = FALSE,
              line.color = scales::alpha(
                "white",
                0.01
              ),
              label.color = "black",
              r0 = 0,
              r1 = 0.1,
              cex = 0.7
            )
          }
        }
      }
    }

    if(save_plots) {
      dev.off()
    }
  }


  invisible(
    list(
      gr_de = gr_de,
      gr_drivers = gr_drivers
    )
  )
}
